-- Periodic invoices retain a full invoice template, generated instances, and added flags.
CREATE TABLE periodic_invoice (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  legacy_id INTEGER NOT NULL UNIQUE,
  company_id BIGINT NOT NULL,
  number INTEGER,
  start_date DATE,
  count INTEGER,
  period_months INTEGER,
  description VARCHAR(4096),
  period_start DATE,
  period_end DATE,
  append_period BOOLEAN NOT NULL,
  append_information BOOLEAN NOT NULL,
  information_text VARCHAR(4096),
  template_number INTEGER,
  template_date DATE,
  template_due_date DATE,
  template_customer_number VARCHAR(255),
  template_customer_name VARCHAR(255),
  template_our_contact_person VARCHAR(255),
  template_customer_contact_person VARCHAR(255),
  template_delay_interest DECIMAL(100,30),
  template_currency_code VARCHAR(255),
  template_payment_term_name VARCHAR(255),
  template_delivery_term_name VARCHAR(255),
  template_delivery_way_name VARCHAR(255),
  template_tax_free BOOLEAN NOT NULL,
  template_invoice_text VARCHAR(16384),
  template_tax_rate_1 DECIMAL(100,30),
  template_tax_rate_2 DECIMAL(100,30),
  template_tax_rate_3 DECIMAL(100,30),
  template_eu_sale_commodity BOOLEAN NOT NULL,
  template_eu_sale_third_party_commodity BOOLEAN NOT NULL,
  template_printed BOOLEAN NOT NULL,
  template_invoice_type VARCHAR(32),
  template_currency_rate DECIMAL(100,30),
  template_customer_order_number VARCHAR(1024),
  template_ocr_number VARCHAR(255),
  template_entered BOOLEAN NOT NULL,
  template_reminder_count INTEGER NOT NULL,
  template_interest_invoiced BOOLEAN NOT NULL,
  template_stock_influencing BOOLEAN NOT NULL,
  template_order_numbers VARCHAR(4096),
  CONSTRAINT fk_periodic_company FOREIGN KEY(company_id) REFERENCES company(id),
  CONSTRAINT fk_periodic_currency FOREIGN KEY(template_currency_code) REFERENCES currency(code),
  CONSTRAINT fk_periodic_payment FOREIGN KEY(template_payment_term_name) REFERENCES payment_term(name),
  CONSTRAINT fk_periodic_delivery_term FOREIGN KEY(template_delivery_term_name) REFERENCES delivery_term(name),
  CONSTRAINT fk_periodic_delivery_way FOREIGN KEY(template_delivery_way_name) REFERENCES delivery_way(name),
  CONSTRAINT uq_periodic_id_scope UNIQUE(id,company_id)
);
CREATE INDEX ix_periodic_company_number ON periodic_invoice(company_id,number);

CREATE TABLE periodic_invoice_template_row (
  periodic_invoice_id BIGINT NOT NULL,
  row_number INTEGER NOT NULL,
  product_number VARCHAR(255),
  description VARCHAR(4096),
  unit_price DECIMAL(100,30),
  quantity DECIMAL(100,30),
  unit_name VARCHAR(255),
  discount DECIMAL(100,30),
  tax_code VARCHAR(32),
  account_number INTEGER,
  project_number VARCHAR(255),
  result_unit_number VARCHAR(255),
  PRIMARY KEY(periodic_invoice_id,row_number),
  CONSTRAINT fk_periodic_row_parent FOREIGN KEY(periodic_invoice_id) REFERENCES periodic_invoice(id),
  CONSTRAINT fk_periodic_row_unit FOREIGN KEY(unit_name) REFERENCES unit_definition(name)
);

CREATE TABLE periodic_invoice_instance (
  periodic_invoice_id BIGINT NOT NULL,
  row_number INTEGER NOT NULL,
  invoice_number INTEGER,
  invoice_date DATE,
  due_date DATE,
  customer_number VARCHAR(255),
  customer_name VARCHAR(255),
  our_contact_person VARCHAR(255),
  customer_contact_person VARCHAR(255),
  delay_interest DECIMAL(100,30),
  currency_code VARCHAR(255),
  payment_term_name VARCHAR(255),
  delivery_term_name VARCHAR(255),
  delivery_way_name VARCHAR(255),
  tax_free BOOLEAN NOT NULL,
  invoice_text VARCHAR(16384),
  tax_rate_1 DECIMAL(100,30),
  tax_rate_2 DECIMAL(100,30),
  tax_rate_3 DECIMAL(100,30),
  eu_sale_commodity BOOLEAN NOT NULL,
  eu_sale_third_party_commodity BOOLEAN NOT NULL,
  printed BOOLEAN NOT NULL,
  invoice_type VARCHAR(32),
  currency_rate DECIMAL(100,30),
  customer_order_number VARCHAR(1024),
  ocr_number VARCHAR(255),
  entered BOOLEAN NOT NULL,
  reminder_count INTEGER NOT NULL,
  interest_invoiced BOOLEAN NOT NULL,
  stock_influencing BOOLEAN NOT NULL,
  order_numbers VARCHAR(4096),
  added BOOLEAN NOT NULL,
  PRIMARY KEY(periodic_invoice_id,row_number),
  CONSTRAINT fk_periodic_instance_parent FOREIGN KEY(periodic_invoice_id) REFERENCES periodic_invoice(id),
  CONSTRAINT fk_periodic_instance_currency FOREIGN KEY(currency_code) REFERENCES currency(code),
  CONSTRAINT fk_periodic_instance_payment FOREIGN KEY(payment_term_name) REFERENCES payment_term(name),
  CONSTRAINT fk_periodic_instance_delivery_term FOREIGN KEY(delivery_term_name) REFERENCES delivery_term(name),
  CONSTRAINT fk_periodic_instance_delivery_way FOREIGN KEY(delivery_way_name) REFERENCES delivery_way(name)
);

CREATE TABLE periodic_invoice_instance_row (
  periodic_invoice_id BIGINT NOT NULL,
  instance_row_number INTEGER NOT NULL,
  row_number INTEGER NOT NULL,
  product_number VARCHAR(255),
  description VARCHAR(4096),
  unit_price DECIMAL(100,30),
  quantity DECIMAL(100,30),
  unit_name VARCHAR(255),
  discount DECIMAL(100,30),
  tax_code VARCHAR(32),
  account_number INTEGER,
  project_number VARCHAR(255),
  result_unit_number VARCHAR(255),
  PRIMARY KEY(periodic_invoice_id,instance_row_number,row_number),
  CONSTRAINT fk_periodic_instance_row_parent FOREIGN KEY(periodic_invoice_id,instance_row_number)
    REFERENCES periodic_invoice_instance(periodic_invoice_id,row_number),
  CONSTRAINT fk_periodic_instance_row_unit FOREIGN KEY(unit_name) REFERENCES unit_definition(name)
);
