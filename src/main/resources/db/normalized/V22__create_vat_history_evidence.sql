-- Recorded history claims only: no accepted baseline, posting registry or inferred coverage.
CREATE TABLE vat_history_evidence (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  company_id BIGINT NOT NULL,
  accounting_year_id BIGINT NOT NULL,
  fiscal_first DATE NOT NULL,
  fiscal_last DATE NOT NULL,
  recorded_at TIMESTAMP(9) WITH TIME ZONE NOT NULL,
  recorded_by VARCHAR(255) NOT NULL,
  evidence_reference VARCHAR(4096) NOT NULL,
  CONSTRAINT fk_vat_evidence_year FOREIGN KEY (accounting_year_id, company_id)
    REFERENCES accounting_year(id, company_id) ON DELETE CASCADE,
  CONSTRAINT ck_vat_evidence_dates CHECK (fiscal_first <= fiscal_last),
  CONSTRAINT ck_vat_evidence_actor CHECK (CHAR_LENGTH(TRIM(recorded_by)) > 0),
  CONSTRAINT ck_vat_evidence_reference CHECK (CHAR_LENGTH(TRIM(evidence_reference)) > 0)
);

CREATE TABLE vat_history_coverage (
  evidence_id BIGINT NOT NULL,
  position INTEGER NOT NULL,
  period_first DATE NOT NULL,
  period_last DATE NOT NULL,
  PRIMARY KEY (evidence_id, position),
  CONSTRAINT fk_vat_coverage_evidence FOREIGN KEY (evidence_id)
    REFERENCES vat_history_evidence(id) ON DELETE CASCADE,
  CONSTRAINT ck_vat_coverage_position CHECK (position > 0),
  CONSTRAINT ck_vat_coverage_dates CHECK (period_first <= period_last)
);

CREATE TABLE vat_history_known_settlement (
  evidence_id BIGINT NOT NULL,
  position INTEGER NOT NULL,
  period_first DATE NOT NULL,
  period_last DATE NOT NULL,
  PRIMARY KEY (evidence_id, position),
  CONSTRAINT fk_vat_known_evidence FOREIGN KEY (evidence_id)
    REFERENCES vat_history_evidence(id) ON DELETE CASCADE,
  CONSTRAINT ck_vat_known_position CHECK (position > 0),
  CONSTRAINT ck_vat_known_dates CHECK (period_first <= period_last)
);
